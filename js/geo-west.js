/* The Way — geography of the central Mediterranean, for the voyage to Rome (Acts 27–28).
   Hand-placed coasts at roughly true positions: Italy, Sicily, Malta, Greece, Crete, Lycia and Caria, and the African
   shore. Heights are approximate. */
window.TW = window.TW || {};
(function (TW) {
  const U = TW.U;
  const EX = (lon) => (lon - 11.0) * 86, EY = (lat) => (42.5 - lat) * 111;
  const pts = (a) => a.map((p) => [EX(p[0]), EY(p[1])]);
  function segDist(px, py, ax, ay, bx, by) {
    const dx = bx - ax, dy = by - ay, l = dx * dx + dy * dy;
    const t = l ? U.clamp(((px - ax) * dx + (py - ay) * dy) / l, 0, 1) : 0;
    return Math.hypot(ax + t * dx - px, ay + t * dy - py);
  }
  const lineDist = (px, py, p) => { let d = 1e9; for (let i = 0; i < p.length; i++) { const a = p[i], b = p[(i + 1) % p.length]; d = Math.min(d, segDist(px, py, a[0], a[1], b[0], b[1])); } return d; };
  function inPoly(px, py, p) { let c = false; for (let i = 0, j = p.length - 1; i < p.length; j = i++) if ((p[i][1] > py) !== (p[j][1] > py) && px < ((p[j][0] - p[i][0]) * (py - p[i][1])) / (p[j][1] - p[i][1]) + p[i][0]) c = !c; return c; }
  const G = (d, s) => Math.exp(-(d * d) / (2 * s * s));

  const ITALY = pts([[10.9, 42.6], [14.25, 42.6], [14.25, 42.46], [14.99, 42.0], [15.6, 41.95], [16.2, 41.9], [15.9, 41.6], [16.87, 41.13], [17.94, 40.64], [18.49, 40.15],
    [18.36, 39.8], [17.99, 40.05], [17.24, 40.47], [16.6, 40.1], [16.6, 39.6], [17.13, 39.08], [17.15, 38.9], [16.55, 38.45], [16.06, 37.92], [15.65, 38.0], [15.65, 38.11],
    [15.71, 38.25], [15.85, 38.6], [16.1, 38.7], [16.0, 38.95], [15.8, 39.6], [15.6, 40.05], [14.9, 40.25], [14.75, 40.68], [14.35, 40.6], [14.25, 40.84], [14.05, 40.82],
    [13.9, 41.0], [13.57, 41.21], [13.25, 41.28], [12.63, 41.45], [12.29, 41.74], [11.9, 42.0], [11.8, 42.09], [11.4, 42.4], [10.9, 42.42]]);
  const SICILY = pts([[12.5, 38.02], [12.73, 38.18], [13.36, 38.12], [14.02, 38.04], [15.24, 38.27], [15.65, 38.27], [15.29, 37.85], [15.09, 37.5], [15.29, 37.07],
    [15.13, 36.69], [14.25, 37.06], [13.58, 37.28], [13.08, 37.5], [12.59, 37.65], [12.43, 37.8]]);
  const BALKANS = pts([[18.5, 42.6], [30.6, 42.6], [30.6, 41.2], [29.0, 41.05], [27.5, 40.97], [26.95, 40.62], [26.67, 40.42], [26.18, 40.05], [26.3, 40.5], [26.0, 40.75],
    [24.4, 40.9], [23.7, 40.65], [22.95, 40.6], [22.6, 40.2], [22.95, 39.4], [22.9, 38.9], [23.6, 38.5], [24.05, 38.15], [23.95, 37.65], [23.2, 37.6], [23.05, 37.0],
    [23.2, 36.45], [22.8, 36.55], [22.4, 36.45], [22.1, 36.75], [21.7, 37.0], [21.4, 37.7], [21.1, 38.3], [20.75, 38.95], [20.2, 39.6], [20.0, 39.87], [19.48, 40.47],
    [19.44, 41.32], [19.4, 41.9]]);
  const CORINTH = pts([[21.7, 38.25], [22.9, 37.95], [22.95, 38.05], [21.75, 38.4]]);
  const ASIA = pts([[26.18, 40.05], [26.7, 40.32], [28.0, 40.38], [30.6, 40.4], [30.6, 36.3], [29.98, 36.24], [29.64, 36.2], [29.1, 36.62], [28.4, 36.75], [27.37, 36.68],
    [27.4, 37.05], [27.25, 37.45], [27.27, 37.95], [26.3, 38.3], [26.75, 38.65], [26.7, 39.3], [26.1, 39.5]]);
  const CRETE = pts([[23.52, 35.6], [23.6, 35.27], [24.2, 35.5], [24.9, 35.42], [25.6, 35.32], [26.3, 35.3], [26.25, 35.05], [25.8, 34.98], [24.8, 34.93], [24.2, 35.2], [23.6, 35.22]]);
  const AFRICA = [pts([[10.9, 32.4], [10.9, 32.95], [13.2, 32.92], [14.3, 32.62], [14.6, 32.4]]), pts([[19.9, 32.4], [20.6, 32.75], [21.5, 32.9], [22.6, 32.8], [23.2, 32.6], [23.4, 32.4]])];
  const ISLES = [[14.43, 35.9, 0.12, 0.07], [14.25, 36.04, 0.06, 0.04], [24.08, 34.84, 0.05, 0.03], [28.0, 36.2, 0.25, 0.15], [19.85, 39.6, 0.15, 0.2], [20.6, 38.2, 0.15, 0.15],
    [20.85, 37.8, 0.1, 0.1], [25.45, 37.05, 0.12, 0.15], [25.15, 37.05, 0.08, 0.08], [24.9, 37.85, 0.14, 0.1], [26.25, 39.18, 0.3, 0.17], [26.0, 38.4, 0.12, 0.25],
    [26.8, 37.73, 0.22, 0.08], [27.15, 36.85, 0.2, 0.06], [12.0, 36.8, 0.07, 0.05]];
  const PEAKS = [[15.0, 37.75, 3300, 12], [24.77, 35.23, 2400, 9], [24.1, 35.3, 2400, 9], [14.4, 40.82, 1200, 6], [13.8, 41.9, 2500, 40], [15.9, 39.9, 2000, 30],
    [16.2, 38.5, 1900, 18], [21.3, 39.8, 2400, 40], [22.35, 37.0, 2300, 14], [22.35, 40.08, 2900, 12], [20.2, 40.8, 2000, 30], [29.5, 37.0, 2500, 40], [28.0, 37.4, 1500, 30],
    [14.4, 37.7, 1500, 26], [22.2, 37.6, 1500, 22]];

  function sampleWest(lon, lat) {
    const px = EX(lon), py = EY(lat);
    let isle = false;
    for (const s of ISLES) if (((lon - s[0]) / s[2]) ** 2 + ((lat - s[1]) / s[3]) ** 2 < 1) { isle = true; break; }
    const polys = [ITALY, SICILY, ASIA, CRETE].concat(AFRICA);
    const land = isle || polys.some((p) => inPoly(px, py, p)) || (inPoly(px, py, BALKANS) && !inPoly(px, py, CORINTH));
    if (!land) return { e: -80, water: 'sea', arid: 0 };
    const dCoast = isle ? 3 : Math.min.apply(null, polys.concat([BALKANS, CORINTH]).map((p) => lineDist(px, py, p)));
    let e = 20 + Math.min(isle ? 120 : 600, dCoast * 5);
    for (const m of PEAKS) e = Math.max(e, m[2] * G(Math.hypot(px - EX(m[0]), py - EY(m[1])), m[3]) + e * 0.3);
    e += (U.fbm(px * 0.03, py * 0.03, 91, 4) - 0.5) * 300 * U.clamp(dCoast / 20, 0.2, 1);
    e = Math.max(e, 5);
    const arid = U.clamp(U.smooth(37.0, 33.0, lat) * 0.7 + (isle ? 0.2 : 0), 0, 0.85);
    return { e: e, water: null, arid: arid };
  }
  TW.Geo.west = sampleWest;
})(window.TW);
