#!/usr/bin/env node
/* The Way — turn a public-domain Bible file into a version file the game can ship.
   Usage:
     node tools/import-bible.mjs eng-asv_vpl.txt --id ASV --name "American Standard Version" --lang en
     node tools/import-bible.mjs spaRV1909_vpl.txt --id RV1909 --name "Reina-Valera 1909" --lang es
   Options: --license "Public domain" (default)   --all  keep every verse, not only the ones the game uses
   Writes bible/<ID>.js. Then add <script src="bible/<ID>.js"></script> after bible/versions.js in index.html.
   Accepts the same formats as the in-game importer: eBible.org VPL ("MRK 2:1 ..."), "Book 2:1 ..." lines in English or
   Spanish, Project Gutenberg numbered text, and JSON. Re-run it when new episodes add new passages. */
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const valued = new Set(['--id', '--name', '--short', '--lang', '--license']);
const input = args.find((a, i) => !a.startsWith('--') && !valued.has(args[i - 1]));
if (!input) { console.error('Usage: node tools/import-bible.mjs <file> --id ASV --name "American Standard Version" --lang en'); process.exit(1); }
const ctx = { console, localStorage: { getItem: () => null, setItem() {} } };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ['scripture', 'scripture2', 'scripture3', 'scripture4', 'scripture5', 'scripture6', 'scripture7', 'scripture8', 'scripture9', 'scripture10', 'bible']) vm.runInContext(fs.readFileSync(path.join(root, 'js', f + '.js'), 'utf8'), ctx);
const B = ctx.TW.Bible;
const all = B.parse(fs.readFileSync(input, 'utf8'));
const kept = args.includes('--all') ? { text: all, matched: Object.values(all).reduce((n, b) => n + Object.keys(b).length, 0), needed: B.needed().length } : B.filter(all);
const id = String(opt('id', 'BIBLE')).toUpperCase().replace(/[^A-Z0-9]/g, '');
const version = { id, name: opt('name', id), short: opt('short', id), lang: opt('lang', 'en'), license: opt('license', 'Public domain'), text: kept.text };
const out = path.join(root, 'bible', id + '.js');
fs.writeFileSync(out, '/* The Way — ' + version.name + ' (' + version.license + '). Generated by tools/import-bible.mjs. */\nTW.Bible.add(' + JSON.stringify(version) + ');\n');
console.log('Wrote ' + path.relative(root, out) + ': ' + kept.matched + ' verses' + (args.includes('--all') ? '' : ' of the ' + kept.needed + ' the game uses') + '.');
const missing = B.needed().filter(([bk, cv]) => !(kept.text[bk] && kept.text[bk][cv]));
if (missing.length) console.log('Missing ' + missing.length + ' (shown from the WEB in the game), e.g. ' + missing.slice(0, 5).map((m) => m.join(' ')).join(', '));
